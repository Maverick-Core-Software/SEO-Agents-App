import { addDays, chicagoToday, mondayOfWeek } from '../lib/week.js';

const thisMonday = mondayOfWeek(chicagoToday());

/** `weeksAgo` 0 = current week; `dayIndex` 0 = Monday. */
function d(weeksAgo, dayIndex) {
  return addDays(thisMonday, -7 * weeksAgo + dayIndex);
}

function calPost({ id, platform, weeksAgo, dayIndex, status, ...rest }) {
  const post_date = d(weeksAgo, dayIndex);
  const posted = status === 'posted' || status === 'done';
  return {
    id,
    run_id: `fix-run-w${weeksAgo}`,
    platform,
    day: dayIndex + 1,
    post_date,
    type: rest.type || 'photo',
    service: rest.service || 'Electrical',
    hook: rest.hook || rest.service || 'Grizzly weekly post',
    body: rest.body || rest.hook || rest.service || '',
    cta: rest.cta || 'Call Grizzly',
    hashtags: rest.hashtags || '#GrizzlyElectrical #DFWElectrician',
    photo_file: rest.photo_file || 'panel-upgrade.jpg',
    media_status: rest.media_status || 'photo',
    status,
    platform_post_id: posted ? `pid-${id}` : null,
    error: rest.error || null,
  };
}

